# https://wiki.hypr.land/Configuring/Basics/Monitors/
# for every monitor detected by hyprctl, writes hl.monitor + hl.workspace_rule entries to ~/.config/hypr/monitors.lua
#!/usr/bin/env bash
set -euo pipefail
echo "Configuring monitor layout in monitors.lua..."
CONF="$HOME/.config/hypr/monitors.lua"
MONITORS=($(hyprctl monitors all | awk '/^Monitor / {gsub(/^Monitor |:$/,""); print $1}'))
echo "Found ${#MONITORS[@]} monitors."

echo "-- generated by MONITOR_CONFIG.sh" > "$CONF"

# for every monitor prompt the user for position transformation and workspace number
INDEX=1
for m in "${MONITORS[@]}"; do
    echo "Configuring monitor: $m"
    read -rp "Enter position for monitor $m (options: auto, auto-left, auto-right, auto-up, auto-down) [default: auto]: " POS
    POS=${POS:-auto}
    read -rp "Enter transform for monitor $m (options: 0, 1, 2, 3) [default: 0]: " TRANSFORM
    TRANSFORM=${TRANSFORM:-0}
    read -rp "Enter workspace number to assign to monitor $m [default: $INDEX]: " WS
    WS=${WS:-$INDEX}
    INDEX=$((INDEX + 1))
    echo "Adding monitor $m (position $POS, transform $TRANSFORM, workspace $WS)"
    echo "hl.monitor({ output = \"$m\", mode = \"highres\", position = \"$POS\", scale = 1, transform = $TRANSFORM })" >> "$CONF"
    echo "hl.workspace_rule({ workspace = \"$WS\", monitor = \"$m\" })" >> "$CONF"
done

echo "Monitor configuration updated in $CONF."
